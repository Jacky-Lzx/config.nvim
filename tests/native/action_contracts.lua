vim.opt.rtp:prepend(assert(vim.env.NVIM_CONFIG_ROOT))
local actions = dofile(vim.env.NVIM_CONFIG_ROOT .. "/tests/support/actions.lua")
local bindings = require("config.bindings")
vim.g.mapleader = ","
local calls = 0
local callback = function()
  calls = calls + 1
end
local function rejects(run, message)
  local ok, err = pcall(run)
  assert(not ok and tostring(err):find(message, 1, true), tostring(err))
end
local function configure(lhs)
  bindings.set("fixture", { { lhs, callback, id = "fixture.run", mode = { "n", "x" } } })
end
configure("<leader>xy")
assert(actions.input("fixture.run") == ",xy")
assert(actions.binding("fixture.run", "x").owner == "fixture")
vim.api.nvim_feedkeys(actions.keys("fixture.run"), "xt", false)
assert(calls == 1)
configure("<A-p>")
assert(actions.input("fixture.run") == "\27p")
assert(vim.fn.maparg(",xy", "n") == "", "Old key survived remapping")
configure("<leader>new")
vim.api.nvim_feedkeys(actions.keys("fixture.run"), "xt", false)
assert(calls == 2, "Remapped action changed its result")
assert(actions.audit() == 2)
bindings.set("collision", { { "<leader>new", function() end } })
rejects(function()
  actions.audit()
end, "replaced")
bindings.set("collision", {})
configure("<leader>new")
vim.keymap.set("n", "<leader>new", function() end)
rejects(function()
  actions.binding("fixture.run")
end, "replaced")
configure("<leader>new")
vim.keymap.set("n", "<leader>new", callback, { buffer = true })
rejects(function()
  actions.binding("fixture.run")
end, "scope")
vim.keymap.del("n", "<leader>new", { buffer = true })
rejects(function()
  actions.binding("fixture.run", "i")
end, "Missing declared action")
bindings.set("duplicate", { { "<leader>other", callback, id = "fixture.run" } })
rejects(function()
  actions.binding("fixture.run")
end, "Ambiguous action")
bindings.set("duplicate", {})
bindings.set("fixture", {})
rejects(function()
  actions.binding("fixture.run")
end, "Missing declared action")
bindings.set("filetype", { { "<leader>ft", callback, id = "fixture.ft", ft = "lua" } })
rejects(function()
  actions.binding("fixture.ft")
end, "Missing declared action")
vim.bo.filetype = "lua"
assert(actions.binding("fixture.ft"))
print(
  "Action contracts: remapping, real execution, modes, filetypes, missing/ambiguous actions and mapping replacement passed"
)
