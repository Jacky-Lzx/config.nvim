local root = assert(vim.env.NVIM_CONFIG_ROOT)
local temp = assert(vim.env.NVIM_TEST_TMP)
vim.opt.rtp:prepend(root)
local files = require("features.files")
files.setup()
vim.cmd("filetype on")
local function open(name, lines)
  local path = temp .. "/" .. name
  vim.fn.writefile(lines, path)
  vim.cmd.edit(path)
  return vim.api.nvim_get_current_buf()
end
local normal = open("normal.lua", { "local ok = true" })
assert(vim.bo.filetype == "lua" and not vim.b.bigfile and vim.b.completion == nil)
local large = open("large.lua", { string.rep("x", 1600000) })
assert(vim.bo.filetype == "bigfile" and vim.b.bigfile, "Large files must be classified before language consumers")
assert(vim.b.completion == false and vim.b.config_treesitter_disabled and vim.b.ui_tools_disable)
assert(vim.wo.foldmethod == "manual" and vim.wo.statuscolumn == "" and vim.wo.conceallevel == 0)
assert(not vim.treesitter.highlighter.active[large])
local minified = open("minified.json", { string.rep("x", 2000) })
assert(vim.bo.filetype == "bigfile" and vim.b.bigfile)
vim.cmd("vsplit")
assert(vim.wo.foldmethod == "manual" and vim.wo.conceallevel == 0)
vim.cmd.close()
vim.api.nvim_set_current_buf(normal)
assert(not vim.b.bigfile and vim.b.completion == nil, "Large-file policy leaked to another buffer")
vim.api.nvim_buf_delete(large, { force = true })
vim.api.nvim_buf_delete(minified, { force = true })
print(
  "File policy: large/minified detection, FileType ordering, completion/parser/UI guards and buffer isolation passed"
)
